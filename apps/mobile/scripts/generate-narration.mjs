#!/usr/bin/env node
/**
 * Pre-records xTan's landing-page narration with ElevenLabs.
 *
 *   node scripts/generate-narration.mjs            # uses ELEVENLABS_VOICE_ID from the repo .env
 *   NARRATION_VOICE_ID=<id> node scripts/...       # record with a different voice
 *
 * Reads  assets/narration/lines.json  →  writes assets/narration/<id>.mp3
 * and    src/components/character/narration.generated.ts  (static requires for Metro).
 * Only lines whose text/voice changed are re-recorded (see manifest.json), so edits are cheap.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, "..");
const dir = path.join(app, "assets/narration");
const env = Object.fromEntries(
  fs
    .readFileSync(path.resolve(app, "../../.env"), "utf8")
    .split("\n")
    .filter((l) => /^[A-Z0-9_]+=/.test(l))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()]),
);

const apiKey = env.ELEVENLABS_API_KEY;
const voiceId = process.env.NARRATION_VOICE_ID || env.ELEVENLABS_VOICE_ID;
if (!apiKey || !voiceId) throw new Error("ELEVENLABS_API_KEY / ELEVENLABS_VOICE_ID missing in .env");

const lines = JSON.parse(fs.readFileSync(path.join(dir, "lines.json"), "utf8"));
const manifestPath = path.join(dir, "manifest.json");
const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : {};

for (const [id, { say }] of Object.entries(lines)) {
  const hash = crypto.createHash("sha1").update(`${voiceId}|${say}`).digest("hex");
  const out = path.join(dir, `${id}.mp3`);
  if (manifest[id] === hash && fs.existsSync(out)) {
    console.log(`= ${id} (unchanged)`);
    continue;
  }
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voiceId}?output_format=mp3_44100_128`, {
    method: "POST",
    headers: { "xi-api-key": apiKey, "Content-Type": "application/json" },
    body: JSON.stringify({
      text: say,
      model_id: "eleven_multilingual_v2",
      voice_settings: { stability: 0.45, similarity_boost: 0.8, style: 0.35, use_speaker_boost: true },
    }),
  });
  if (!res.ok) throw new Error(`${id}: ElevenLabs ${res.status} ${await res.text()}`);
  fs.writeFileSync(out, Buffer.from(await res.arrayBuffer()));
  manifest[id] = hash;
  console.log(`✓ ${id}`);
}
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

const generated = `// AUTO-GENERATED by scripts/generate-narration.mjs — do not edit.
/* eslint-disable */
export const NARRATION_AUDIO = {
${Object.keys(lines)
  .map((id) => `  ${JSON.stringify(id)}: require("../../../assets/narration/${id}.mp3"),`)
  .join("\n")}
} as const;
`;
fs.writeFileSync(path.join(app, "src/components/character/narration.generated.ts"), generated);
console.log(`Wrote ${Object.keys(lines).length} clips + narration.generated.ts`);
